package com.totop.app.domain.model

/**
 * 易错题的四种状态（0.6.0 定四态，2026-11-12 撤销「待校对」后为四态）。
 *
 * 为什么状态不只有「错」：
 * 学生抱回来的东西本来就有几种——根本没思路、确实做错、答案还没定论、
 * 以及看完之后想通了。只留「错」会逼着学生把「不会」也当成错题记，
 * 统计里就只剩一个数字，看不出该补什么。
 *
 * 排序即界面顺序：不会 → 错误 → 存疑 → 理解。
 * 最后一个是终态：自评看懂并能自己重做，等同于「过关」，会参与掌握度（见 0.6.0 第七节）。
 *
 * **「待校对」为什么被删**（2026-11-12）：它原本承接「卷面上有手写过程」这一条自动判定，
 * 但那只是「学生写了字」的副作用，并不代表任何可执行的处置。学生既然把题拍进来问，
 * 就说明这道题他还没掌握；答案是否核对过，不该由一次拍照替学生判断。
 * 现在这类记录统一归「不会」——判据见 [decide]。
 *
 * wire 值是持久化与筛选参数的唯一来源，改文案不影响历史数据。
 */
enum class MistakeStatus(
    val wire: String,
    val label: String,
    /** 一句话解释，用在筛选条的说明与详情页。 */
    val hint: String,
) {
    /**
     * 不会：拍了没思路、明说不会，或**写了过程但没定位到错因**。
     *
     * 第三种情况是本轮新增的：学生已经写了过程还要来问，说明这类题的入手方式
     * 还没稳定，归「不会」比归「错误」更诚实——「错误」意味着能指出错在哪一步，
     * 而这里恰恰指不出来。
     */
    UNKNOWN("unknown", "不会", "没思路、明说不会，或写了过程但没定位到错因"),

    /** 定位到第一个错误步骤时落这里；没有记录状态的旧数据也回退到这里。 */
    WRONG("wrong", "错误", "定位到了第一个错误步骤"),

    /**
     * 存疑：AI 的结论与学生转述的「老师给的答案」不一致。
     *
     * 为什么单独一档而不是并进「错误」：这两种情况的处理方式完全相反——
     * 「错误」是该复习、该重做；「存疑」是**答案本身还没定**，在核实之前
     * 复习它等于把一个可能错的结论再背一遍。所以它必须能被筛出来、单独处理。
     */
    DISPUTED("disputed", "存疑", "AI 的解法与老师给的答案不一致，待核实"),

    /** 自评已看懂、能自己重做，等同于「过关」。 */
    UNDERSTOOD("understood", "理解", "看懂了，能自己重做"),

    ;

    companion object {
        /** 历史数据的默认值：0.6.0 之前的记录都是「做错」。 */
        val DEFAULT: MistakeStatus = WRONG

        /**
         * 落库前的唯一自动判定：定位到首个错误步骤 → 「错误」，否则 → 「不会」。
         *
         * 只有两条分支是刻意的：
         * - 「不会」不是「什么都没做」的专属——学生写了过程却还要来问，同样算没掌握；
         * - 「存疑」与「理解」都不由自动判定产生（前者来自老师答案冲突，后者来自学生自评），
         *   所以这里返回不到那两态。
         *
         * 提成函数而不是写在调用处，是为了让这条口径只有一处实现、可被单测直接覆盖。
         */
        fun decide(hasFirstError: Boolean): MistakeStatus = if (hasFirstError) WRONG else UNKNOWN

        /**
         * 已废弃的 wire 值：老数据与旧备份里仍可能出现。
         *
         * 不保留枚举值、也不做数据库迁移——[fromWireOrWrong] 会把它读成「错误」。
         * 常量留在这里，是为了让「旧值读成错误」这件事有据可查，并有测试守着；
         * 否则将来有人调整回退策略时，会不知道这个字符串还有存量数据。
         */
        const val LEGACY_PENDING_CHECK: String = "pending_check"

        /** 按 wire 解析；认不出时返回 null（由调用方决定回退策略）。 */
        fun ofWire(raw: String?): MistakeStatus? =
            entries.firstOrNull { it.wire.equals(raw?.trim(), ignoreCase = true) }

        /**
         * 读取侧的回退：认不出就当「错误」。
         *
         * 回退到 [WRONG] 而不是 null，是因为列表与统计都不接受「无状态」的记录：
         * 一条读不出状态的旧数据如果被当成异常的 null，会在列表里消失，
         * 学生看到的是「错题少了」而不是「有一条读不出来」。
         */
        fun fromWireOrWrong(raw: String?): MistakeStatus = ofWire(raw) ?: DEFAULT
    }
}
