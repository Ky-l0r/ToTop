package com.totop.app.domain.model

/**
 * 输入框「+」菜单里的两种「要解法」提问。
 *
 * 为什么要把「标准解法 / 其他解法」放在输入框的菜单里，而不是挂一条固定入口：
 * 它们都是**围绕当前这道题**的一次追问，只有在已经拿到解答之后才有意义。
 * 旧版把它们做成对话页上一条常驻按钮，于是：
 * - 还没拍题时按钮就在那里，点了只能说「先拍题」，像坏了一样；
 * - 学生每换一道题，按钮的语义都跟着变，位置却不变，很难形成记忆。
 * 挪进输入框菜单后，它天然属于「我现在要对这道题做点什么」这一组动作，
 * 与「从相册选」并列，语义一致。
 *
 * 三个字段各管一件事，不要混用：
 * - [label] 菜单里显示的名字（也用于提示文案）；
 * - [bubble] 发出去之后**留在对话流里的学生气泡**。菜单名是「其他解法」，
 *   但气泡里必须是一句人话，否则回头看聊天记录时会看到一串命令式短语；
 * - [prompt] 真正发给模型的话。它比气泡长得多：要把「这次是例外」「不要硬凑」
 *   这类约束说清楚，否则模型会沿用追问系统提示里「不要重新讲一遍整道题」的口径，
 *   只回一句「就是上面那样」。
 *
 * 刻意不在这两个提问里写任何 `[[订正]]` / `[[核对]]` 标记：
 * 展示一种新做法不该改动已存的答案（新做法算错时尤其危险），
 * 上层对这两类提问一律忽略机器标记，见 `SolveViewModel.sendFollowUp` 的 `respectMarkers`。
 */
enum class SolutionAsk(
    /** 菜单项文字。 */
    val label: String,
    /** 发出去以后留在对话流里的学生气泡（一句人话）。 */
    val bubble: String,
    /** 实际发给模型的追问正文。 */
    val prompt: String,
) {
    /** 要一份干净的参考答案，不带错因点评。 */
    STANDARD(
        label = "标准解法",
        bubble = "请给我这道题的标准解法",
        prompt =
            "请按参考答案的写法，把这道题的标准解法完整写一遍。" +
                "这次可以是完整的，不必担心重复。\n" +
                "要求：\n" +
                "1. 只保留必需的步骤，每一步写清用了什么公式、定理或性质；\n" +
                "2. 不要评价我原来的思路，也不要鼓励的话；\n" +
                "3. 最后一行写「答案：<最终答案>」。",
    ),

    /** 要一份与已有解法不同的做法。 */
    ALTERNATE(
        label = "其他解法",
        bubble = "这道题还有别的做法吗",
        prompt =
            "这道题除了上面那种做法，还有别的解法吗？请给出**不同**的做法，最多两种。\n" +
                "每种说清三件事：\n" +
                "1. 切入点：从哪个条件、哪条性质或哪个图形入手；\n" +
                "2. 关键的一两步（写出式子，不要只说「联立求解」）；\n" +
                "3. 它比原解法快在哪，或者容易错在哪。\n" +
                "如果这题确实只有一种常规做法，就直接说「这题基本只有这一种做法」并说明理由，不要硬凑。",
    ),
}

/**
 * 什么时候能点这两个菜单项。
 *
 * 抽成纯函数是因为它有三条分支、每条都要给一句**不同**的话：
 * 菜单项本身不像按钮那样能变灰（下拉菜单里灰掉的项更容易被当成 bug），
 * 所以统一走「始终可点 + 点不动时说清为什么」这条既有约定
 * （与顶栏「理解」勾选一致）。纯函数也让这三句话能直接单测。
 */
object SolutionAskPolicy {
    /**
     * 返回不能提问的原因；能提问时返回 null。
     *
     * @param hasSolution 当前会话里是否已经有这道题的解答
     * @param solving 是否正在生成（首次解答或上一轮追问都算）
     */
    fun blockedReason(
        kind: SolutionAsk,
        hasSolution: Boolean,
        solving: Boolean,
    ): String? =
        when {
            solving -> "还在生成，等这一轮答完再看「" + kind.label + "」"
            hasSolution -> null
            else -> "这道题还没有解答：先拍一张或写一句话问一问，再看「" + kind.label + "」"
        }
}
